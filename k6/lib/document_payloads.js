const PAYLOAD_REPEAT = {
  small: 1,
  medium: 2,
  large: 4,
  xlarge: 8,
};

export const PAYLOAD_SIZES = Object.keys(PAYLOAD_REPEAT);

export function resolvePayloadSize(rawSize) {
  if (!rawSize) {
    return 'large';
  }

  const normalized = rawSize.trim().toLowerCase();
  return PAYLOAD_REPEAT[normalized] ? normalized : 'large';
}

export function buildDocumentText(size = 'large') {
  const payloadSize = resolvePayloadSize(size);
  return Array.from({ length: PAYLOAD_REPEAT[payloadSize] }, () => BASE_TEXT).join('\n\n');
}

export function buildCreateDocumentPayload({ size = 'large', folderId = 0, titlePrefix = '부하테스트 문서' } = {}) {
  const payloadSize = resolvePayloadSize(size);
  return {
    title: `${titlePrefix} ${payloadSize}`,
    text: buildDocumentText(payloadSize),
    paragraphs: [
      {
        blockId: 1,
        content: `대 본 1 (${payloadSize})`,
        role: 'BODY',
      },
    ],
    folderId,
  };
}
